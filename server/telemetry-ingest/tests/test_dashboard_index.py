    def archive(self, capture_id="one", landing_id="landing-one", *, airport="LMML", journal=True, times=(0, .05, .05, .1, 1.2), offset=0, malformed=False, legacy=False, sentinel=False,
                records=None, results_present=True, motion=None, entries=None, summary_updates=None, controllers=False, creator=None, uploader="0.9.1", results_bytes=None):
        summary = {"Id": landing_id, "Airport": airport, "Runway": "31", "AircraftTitle": "A320", "ContactNumber": 1, "ContactCount": 1,
                   "InertialFpm": 196.7, "ImpactPeakG": 1.2, "PeakG2Seconds": 1.4, "ImpactWindowSeconds": 3.08, "ImpactStatus": "Settled", "ClosureReconstructionAvailable": True,
                   "PitchDegrees": -6.9, "BankDegrees": -.3, "GroundSpeedKnots": 110.7, "AirspeedKnots": 121.4,
                   "RunwayGeometry": {"WidthMeters": 58}, "ClosureReconstructionGeometrySource": "FlightModelConfig"}
        if malformed:
            summary["ImpactPeakG"] = float("nan")
            summary["InertialFpm"] = True
        if legacy:
            summary.pop("ImpactPeakG")
        if sentinel:
            summary.update(InertialFpm=NONFINITE_STORAGE_SENTINEL, ClosureReconstructionResidualFpm=NONFINITE_STORAGE_SENTINEL, ClosureReconstructionUncertaintyFpm=NONFINITE_STORAGE_SENTINEL)
        summary.update(summary_updates or {})
        record = {"summary": summary, "pose": {"lat": [35, 35.1], "lon": [14, 14.1], "headingTrueDeg": [310, 310]}}
        content = io.BytesIO()
        with zipfile.ZipFile(content, "w", zipfile.ZIP_DEFLATED) as archive:
            archive.writestr("session.txt", ((creator + "\n") if creator is not None else "") + "aircraft_title=A320\nsimulator=SunRise\ncapture_kind=automatic_landing\n")
            suffix = ",motion_simulation" if motion is not None else ""
            archive.writestr("telemetry.csv", "sequence,simulation_time_s,host_elapsed_s,g_force,controller_0_raw_y_valid" + suffix + "\n" + "".join(f"{n},{t},{n * .01},1,1" + (f",{motion[n]}" if motion is not None else "") + "\n" for n, t in enumerate(times)))
            if controllers:
                archive.writestr("controller-catalogs.json", json.dumps({"version": 1, "samples": len(times), "catalogs": [""], "transitions": [[0, 0]]}))
            if results_present:
                archive.writestr("landing-results.json", results_bytes if results_bytes is not None else json.dumps({"records": [record] if records is None else records}))
            if journal:
                archive.writestr("decisions.json", json.dumps({"truncated": False, "entries": entries if entries is not None else [{"component": "replay.inputs", "code": "axis_selected", "reason": "selected", "time_seconds": 0, "details": {"role": 0, "source_index": 1, "correlation": .71}}, {"component": "replay.track", "code": "track_created", "reason": "created", "time_seconds": 0, "details": {"frames": 2}}]}))
            archive.comment = capture_id.encode()
        data = content.getvalue()
        path = self.root / "accepted" / f"{capture_id}.zip"
        path.write_bytes(data)
        with zipfile.ZipFile(io.BytesIO(data)) as archive:
            expanded = sum(info.file_size for info in archive.infolist())
        row = (capture_id, "anonymous-installation", hashlib.sha256(data).hexdigest(), f"accepted/{capture_id}.zip", int(time.time()) + offset, len(data), expanded, len(times), 6, uploader, "automatic_landing")
        self.db.execute("INSERT INTO captures VALUES(?,?,?,?,?,?,?,?,?,?,?)", row)
        self.db.commit()
        return path

    def test_creator_and_uploader_versions_are_independent_across_cache_and_filters(self):
        path = self.archive(creator="Generated by MSFS Landing Stats 0.9.4 by Example author", uploader="0.9.7")
        original = path.read_bytes()
        source = self.db.execute("SELECT * FROM captures").fetchall()
        # A version-5 positive cache must also be rebuilt, without changing the
        # archive hash or the signed receiver metadata.
        with self.index._connect_cache() as connection:
            connection.execute("INSERT INTO archive_index VALUES(?,?,?,?,?,?)",
                               (hashlib.sha256(original).hexdigest(), 5, time.time(), "{}", "{}", None))
        self.index._refresh()
        for item in (self.index.list_captures()["items"][0], self.index.capture("one"), self.index.summary()["recent"][0]):
            self.assertEqual("0.9.4", item["creator_version"])
            self.assertEqual("0.9.7", item["uploader_version"])
            self.assertEqual("0.9.7", item["app_version"])  # Legacy API is the signed upload version.
        self.assertEqual(1, self.index.list_captures(creator_version="0.9.4", uploader_version="0.9.7")["total"])
        self.assertEqual(0, self.index.list_captures(creator_version="0.9.7")["total"])
        self.assertEqual(0, self.index.list_captures(uploader_version="0.9.4")["total"])
        self.assertEqual(1, self.index.list_captures(q="0.9.4")["total"])
        self.assertEqual(1, self.index.list_captures(q="0.9.7")["total"])
        breakdowns = self.index.summary()["breakdowns"]
        self.assertEqual([{"name": "0.9.4", "count": 1}], breakdowns["creator_versions"])
        self.assertEqual([{"name": "0.9.7", "count": 1}], breakdowns["uploader_versions"])
        with patch("app.dashboard_index._index_archive", side_effect=AssertionError("must use refreshed cache")):
            self.index._refresh()
        self.assertEqual("0.9.4", self.index.capture("one")["creator_version"])
        self.assertEqual(source, self.db.execute("SELECT * FROM captures").fetchall())
        self.assertEqual(original, path.read_bytes())

