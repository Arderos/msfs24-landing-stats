    def test_large_accepted_results_are_reindexed_at_the_receiver_limit(self):
        from app.validation import MAXIMUM_RESULT_BYTES
        self.assertEqual(MAXIMUM_RESULT_BYTES, MAX_RESULTS_BYTES)
        for name, size in (("previously-rejected", 26_430_049), ("boundary", MAXIMUM_RESULT_BYTES)):
            # Whitespace padding exercises the actual byte boundary without a
            # huge test-only object graph or committed private capture.
            results = b'{"records":[{"summary":{"Id":"large","Airport":"LMML"}}]}'
            path = self.archive(name, results_bytes=results + b" " * (size - len(results)))
            digest = hashlib.sha256(path.read_bytes()).hexdigest()
            with self.index._connect_cache() as connection:
                connection.execute("INSERT INTO archive_index VALUES(?,?,?,?,?,?)", (digest, 5, time.time(), None, None,
                                   "ValueError: landing-results.json exceeds dashboard read limit"))
        self.index._refresh()
        self.assertEqual(2, self.index.summary()["index"]["indexed"])
        self.assertEqual(0, self.index.summary()["index"]["errors"])
        self.assertEqual(1, self.index.summary()["totals"]["unique_landings"])
        self.assertEqual(1, self.index.capture("previously-rejected")["landing_count"])

